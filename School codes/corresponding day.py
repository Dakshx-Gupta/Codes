a = int(input("Enter the number for corresponding day of week: "))
if a == 1:
    print("Day - Monday")
if a == 2:
    print("Day - Tuesday")
if a == 3:
    print("Day - Wednesday")
if a == 4:
    print("Day - Thursday")
if a == 5:
    print("Day - Friday")
if a == 6:
    print("Day - Saturday")
if a == 7:
    print("Day - Sunday")
if a > 7:
    print("Invalid Day Number")
 