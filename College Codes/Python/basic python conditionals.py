#if else
a = 10
if a > 10:
    print("Hellow")
else:
    print("Bye-Bye")

 
# nested if else
b = 20
if b > 15:
    if b <= 20:
        print("Nice")
else:
    print("Okay")


#if-elif-else
c = 30
if c > 30:
    print("Good")
elif c == 30:
    print("Amazing")
else:
    print("Bad")

# ternary 
d = 10
e = 15
f = "True" if d > e else "False"
print(f)
